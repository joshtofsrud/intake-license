def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    root = pathlib.Path(a.root).resolve()
    if not (root / "routes" / "web.php").exists():
        print(f"ERROR: not an intake repo: {root}", file=sys.stderr)
        sys.exit(2)
    mode = "APPLY" if a.apply else "DRY-RUN"
    print(f"=== patch-158-G10 [{mode}] target={root} ===\n")

    any_changed = False
    for rel, b64 in FILES.items():
        p = root / rel
        if not p.exists():
            print(f"ERROR: missing {rel}", file=sys.stderr); sys.exit(2)
        if MARKER.encode() in p.read_bytes():
            print(f"  already_applied: {rel}")
            continue
        if a.apply:
            p.write_bytes(base64.b64decode(b64.replace("\n", "")))
        print(f"  {'written' if a.apply else 'would_write'}: {rel}")
        any_changed = True

    if a.apply and any_changed:
        print()
        print("Done. Next:")
        print("  git add resources/")
        print("  git commit -m \"patch-158-G10: persistent Categories link on inventory index\"")
        print("  git push")
        print()
        print("On droplet:")
        print("  git pull && php artisan view:clear")

if __name__ == "__main__":
    main()
