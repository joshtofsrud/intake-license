OLD_ROUTE = r"""            Route::get('/deliveries',                           [TenantControllers\DeliveriesController::class, 'index'])->name('deliveries.index');"""

NEW_ROUTE = r"""            Route::get('/deliveries',                           [TenantControllers\DeliveriesController::class, 'index'])->name('deliveries.index');
            // MARKER-PATCH-152B — create + edit + complete + cancel
            Route::post('/deliveries',                           [TenantControllers\DeliveriesController::class, 'store'])->name('deliveries.store');
            Route::patch('/deliveries/{id}',                     [TenantControllers\DeliveriesController::class, 'update'])->name('deliveries.update');
            Route::patch('/deliveries/{id}/complete',            [TenantControllers\DeliveriesController::class, 'complete'])->name('deliveries.complete');
            Route::patch('/deliveries/{id}/cancel',              [TenantControllers\DeliveriesController::class, 'cancel'])->name('deliveries.cancel');"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    root = pathlib.Path(a.root).resolve()
    if not (root / "routes" / "web.php").exists():
        print(f"ERROR: not an intake repo: {root}", file=sys.stderr)
        sys.exit(2)
    mode = "APPLY" if a.apply else "DRY-RUN"
    print(f"=== patch-152-b [{mode}] target={root} ===\n")

    # Write embedded files
    for rel, b64 in FILES.items():
        p = root / rel
        content = base64.b64decode(b64.replace("\n", ""))
        if p.exists() and MARKER.encode() in p.read_bytes():
            print(f"  already_applied: {rel}")
            continue
        if a.apply:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(content)
        print(f"  {'written' if a.apply else 'would_write'}: {rel}")

    # Route edit
    routes = root / "routes" / "web.php"
    t = routes.read_text()
    if MARKER in t:
        print("  already_applied: routes")
    elif OLD_ROUTE not in t:
        print("  ERROR: route anchor missing", file=sys.stderr)
        sys.exit(2)
    else:
        if a.apply:
            routes.write_text(t.replace(OLD_ROUTE, NEW_ROUTE, 1))
        print(f"  {'applied' if a.apply else 'would_apply'}: routes (store/update/complete/cancel)")

    if a.apply:
        print()
        print("Done. Next:")
        print("  git status")
        print("  git add -A")
        print("  git commit -m \"patch-152-b: deliveries\"")
        print("  git push")

if __name__ == "__main__":
    main()
