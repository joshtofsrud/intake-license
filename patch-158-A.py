def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    root = pathlib.Path(a.root).resolve()
    if not (root / "routes" / "web.php").exists():
        print(f"ERROR: not an intake repo: {root}", file=sys.stderr)
        sys.exit(2)
    mode = "APPLY" if a.apply else "DRY-RUN"
    print(f"=== patch-158-A [{mode}] target={root} ===\n")

    any_changed = False
    for rel, b64 in FILES.items():
        p = root / rel
        content = base64.b64decode(b64.replace("\n", ""))
        if p.exists() and MARKER.encode() in p.read_bytes():
            print(f"  already_applied: {rel}")
            continue
        if a.apply:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(content)
        print(f"  {'written' if a.apply else 'would_write'}: {rel}")
        any_changed = True

    if a.apply and any_changed:
        print()
        print("Done. Next:")
        print("  git add app/ database/")
        print("  git commit -m \"patch-158-A: multi-asset foundation (schema + models)\"")
        print("  git push")
        print()
        print("On droplet:")
        print("  git pull")
        print("  php artisan migrate --force")
        print("  php artisan optimize:clear")
        print("  # no fpm restart needed — no controller/route changes")

if __name__ == "__main__":
    main()
