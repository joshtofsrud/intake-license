  <p class="lede">A SAFE is not a loan and not shares. It pays no interest, has no maturity date, and
    there is no schedule on which money comes back. What it does is convert: at the next priced equity
    round, it becomes stock at the better of the round price or the $1.5M cap.</p>

  <div class="ctx-cards" style="margin-top:20px">
    <div class="ctx-card"><div class="n">Convert</div><div class="k">The expected path</div>
      <p>A future priced round turns the SAFE into stock. Holding stock is not the same as holding money —
        it becomes cash only at an acquisition, or at a later round where existing holders are allowed to
        sell.</p></div>
    <div class="ctx-card"><div class="n">Acquire</div><div class="k">The realistic exit</div>
      <p>Vertical software of this kind is usually bought rather than floated — by a larger platform, an
        industry group, or a private buyer. That is the outcome this is built toward, and there is no
        timetable on it.</p></div>
    <div class="ctx-card"><div class="n">Never</div><div class="k">The honest case</div>
      <p>If there is no priced round and no sale, the SAFE never converts and the money does not come
        back. Most early-stage investments end here. This should be money you can lose without it
        changing anything for you.</p></div>
    <div class="ctx-card"><div class="n">No</div><div class="k">Things this is not</div>
      <p>No dividend, no buyback, no interest, no redemption on demand, and no secondary market to sell
        into. If liquidity on a timetable matters to you, this is the wrong instrument.</p></div>
  </div>

