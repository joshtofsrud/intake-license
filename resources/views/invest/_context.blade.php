  <p class="sub">Why bike first</p>
  <h2>The hardest version of the problem.</h2>
  <p class="lede">Specialty bike is a service business, a retail business and a rental business at once
    — the hardest version to build, and the reason the core came out general. Booking, work orders,
    retail, inventory, payments and customers are what every service business runs on. Everything
    industry-specific sits on top as a pack, switched on per business, so a new trade is a pack rather
    than a rebuild.</p>

  <div class="ctx-cards">
