<section><div class="wrap">
  <h2>What has to go right.</h2>

  <div class="risk">
    <p><b>Shops have to pay.</b> Nobody has yet paid a subscription, so willingness to pay is unproven at
      scale. Against that: pricing is published rather than theoretical, and a founding shop is
      converting its full point of sale now.</p>
    <p><b>One person has to become two.</b> Intake is built and run by a single founder, which caps how
      fast anything moves and concentrates the risk in one place. This raise is aimed squarely at that —
      but the dependency does not disappear the day the money lands.</p>
    <p><b>The channel has to earn its cost.</b> The founding rep agreement pays 25% of subscription for a
      dealer's first year and 15% after, across eight states. That is the acquisition cost, not an
      addition to one — and these are founding terms for the first territory; later agreements are
      expected to be lower.</p>
    <p><b>The payments rate has to be negotiated.</b> Processing runs at straight pass-through today and
      earns nothing. Strip the 25 bps out entirely and year two is $858k rather than $1.07M — the base
      business does not depend on it.</p>
    <p><b>Pricing has to settle.</b> Tier and pack pricing is still being consolidated, so the figures
      here use currently published rates and may move. The direction of travel is simpler packaging, not
      higher prices.</p>
    <p><b>A SAFE may never convert.</b> It converts at a priced equity round, or pays out in a sale or
      dissolution. A company that becomes profitable and never raises again triggers none of those, and
      the SAFE would simply remain outstanding. Most early-stage investments return nothing; this should
      be money an investor can lose without it changing anything for them.</p>
    <p><b>A hard market cuts both ways.</b> Specialty bicycle retail is under real margin pressure. That
      is part of why shops are receptive to cutting software cost — and part of why some of them will
      close before they ever become customers.</p>
  </div>

  <p class="fine">All forward-looking revenue, account and payment-volume figures are projections built
    from the assumptions shown, so they can be argued with — that is the point of showing them. The
    platform, the integrations, the catalog, the rep agreement and the competitor invoices are not
    projections.</p>
</div></section>
