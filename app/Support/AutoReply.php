<?php

namespace App\Support;

/**
 * MARKER-AUTO-REPLY: is an inbound email a machine answering for a person?
 * Help-desk ticket receipts, out-of-office and "we got your message" replies.
 * Headers decide when the sender set them (RFC 3834 Auto-Submitted, and the
 * vendor flags Exchange, Gmail and help desks use); the wording catches the
 * rest. Such replies are kept and shown, but don't count as a reply.
 */
class AutoReply
{
    private const SUBJECT = [
        '/^\s*(auto(matic)?[\s_-]*(reply|response|answer)|autoreply|autoresponse)\b/i',
        '/\bout of (the )?office\b/i',
        '/\b(on vacation|on leave|away from (the|my) (office|desk))\b/i',
        '/\b(we|i)(\'ve| have) received your (message|email|e-mail|request|enquiry|inquiry)\b/i',
        '/\b(ticket|case|request)\s*(#|number|no\.?)?\s*[\w-]*\s*(has been|was)?\s*(created|received|opened|logged)\b/i',
        '/^\s*\[?(ticket|case|request)\s*#?\s*\d+/i',
        '/\bthank(s| you) for (contacting|reaching out|your (email|message|enquiry|inquiry))\b/i',
        '/\bdelivery status notification\b/i',
    ];

    private const BODY = [
        '/\b(acknowledge|confirm) that we (have )?received your (message|email|e-mail|request)\b/i',
        '/\ba (support )?(ticket|case) (has been|was) (created|opened|logged)\b/i',
        '/\bthis is an automat(ed|ic) (reply|response|message)\b/i',
        '/\b(i am|i\'m) (currently )?(out of (the )?office|away|on vacation|on leave)\b/i',
        '/\bdo not reply to this (email|message)\b/i',
    ];

    /** @param array $headers Postmark's Headers list: [['Name' => ..., 'Value' => ...], ...] */
    public static function detect(array $headers, string $subject, string $body): bool
    {
        foreach ($headers as $h) {
            $name  = strtolower(trim((string) ($h['Name'] ?? '')));
            $value = strtolower(trim((string) ($h['Value'] ?? '')));
            if ($name === 'auto-submitted' && $value !== '' && $value !== 'no') return true;
            if (in_array($name, ['x-autoreply', 'x-autorespond', 'x-autoresponder', 'x-auto-response'], true)) return true;
            if ($name === 'precedence' && in_array($value, ['auto_reply', 'bulk', 'junk'], true)) return true;
            if ($name === 'x-autogenerated' && $value !== '') return true;
            if ($name === 'x-ms-exchange-inbox-rules-loop' || $name === 'x-ms-exchange-generated-message-source') return true;
        }
        return self::detectText($subject, $body);
    }

    /** Wording only: used for replies stored before headers were checked. */
    public static function detectText(string $subject, string $body): bool
    {
        foreach (self::SUBJECT as $re) {
            if (preg_match($re, $subject)) return true;
        }
        $head = mb_substr($body, 0, 1200);
        foreach (self::BODY as $re) {
            if (preg_match($re, $head)) return true;
        }
        return false;
    }

    /** Take back what a reply earned: the +N on the lead score and its "Replied to" timeline line. */
    public static function undoReplyCredit(\App\Models\PlatformInboxMessage $m): void
    {
        $p = \App\Services\Sales\ProspectEngagement::forThread($m);
        if (! $p) return;
        $act = \App\Models\SalesActivity::where('sales_prospect_id', $p->id)->where('type', 'email')
            ->where('body', 'like', 'Replied to: ' . str_replace(['%', '_'], ['\\%', '\\_'], (string) $m->subject) . '%')
            ->orderByDesc('occurred_at')->first();
        if (! $act) return;
        if (preg_match('/\(score \+(\d+)\)/', (string) $act->body, $mm)) {
            $p->forceFill(['lead_score' => max(0, (int) $p->lead_score - (int) $mm[1])])->save();
        }
        $act->delete();
    }
}
