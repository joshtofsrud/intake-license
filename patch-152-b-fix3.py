def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    root = pathlib.Path(a.root).resolve()
    if not (root / "routes" / "web.php").exists():
        print(f"ERROR: not an intake repo: {root}", file=sys.stderr)
        sys.exit(2)
    mode = "APPLY" if a.apply else "DRY-RUN"
    print(f"=== patch-152-b-fix3 [{mode}] target={root} ===")

    files = [
        ("app/Http/Controllers/Tenant/DeliveriesController.php", CTRL_B64, MARKER_CTRL),
        ("resources/views/tenant/deliveries/index.blade.php",    VIEW_B64, MARKER_VIEW),
    ]

    any_changed = False
    for rel, b64, marker in files:
        p = root / rel
        if not p.exists():
            print(f"ERROR: {rel} missing", file=sys.stderr)
            sys.exit(2)
        if marker in p.read_bytes():
            print(f"  already_applied: {rel}")
            continue
        if a.apply:
            p.write_bytes(base64.b64decode(b64.replace("\n", "")))
        print(f"  {'written' if a.apply else 'would_write'}: {rel}")
        any_changed = True

    if a.apply and any_changed:
        print()
        print("Done. Next:")
        print("  git add app/ resources/")
        print("  git commit -m 'patch-152-b-fix3: day-view hour range, week default'")
        print("  git push")

if __name__ == "__main__":
    main()
